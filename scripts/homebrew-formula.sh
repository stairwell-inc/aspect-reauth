#!/usr/bin/env bash
# Prints the Homebrew formula for one aspect-reauth release.
#
# Usage: homebrew-formula.sh VERSION SHA256
#
# The release workflow writes the output to Formula/aspect-reauth.rb in
# stairwell-inc/homebrew-tap, so the formula is generated here and never
# edited in the tap by hand.
set -euo pipefail

if [[ $# -ne 2 ]]; then
  echo "usage: $0 VERSION SHA256" >&2
  exit 2
fi

version=$1
sha256=$2

if [[ ! $version =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "$0: version must be MAJOR.MINOR.PATCH, got '$version'" >&2
  exit 2
fi
if [[ ! $sha256 =~ ^[0-9a-f]{64}$ ]]; then
  echo "$0: sha256 must be 64 lowercase hex digits, got '$sha256'" >&2
  exit 2
fi

cat <<EOF
# Generated by stairwell-inc/aspect-reauth's release workflow
# (scripts/homebrew-formula.sh). Do not edit by hand.
class AspectReauth < Formula
  desc "Keeps Aspect Workflows credentials fresh on a remote devbox"
  homepage "https://github.com/stairwell-inc/aspect-reauth"
  url "https://github.com/stairwell-inc/aspect-reauth/releases/download/v${version}/aspect-reauth-${version}-darwin-universal.tar.gz"
  sha256 "${sha256}"
  license "Apache-2.0"

  depends_on :macos

  def install
    bin.install "aspect-reauth"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/aspect-reauth --version")
  end
end
EOF
